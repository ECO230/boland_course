# Build the unlisted prototype; never publish or alter shared dependencies.
args <- commandArgs(trailingOnly=TRUE)
if (length(args) != 1L) stop("Pass one unused output directory.")
if (dir.exists(args[1])) stop("Output directory already exists; choose a new one.")
if (!requireNamespace("learnr2",quietly=TRUE)) stop("Install the pinned learnr2 package in an isolated library first.")
quarto <- Sys.getenv("QUARTO_PATH", "C:/Program Files/RStudio/resources/app/bin/quarto/bin/quarto.exe")
source <- normalizePath("week06/prototype",winslash="/")
dir.create(args[1],recursive=TRUE)
out <- normalizePath(args[1],winslash="/")
file.copy(file.path(source,c("week6-inference.qmd","tutorial.css","navigation.html")),out)
learnr2::add_live_extension(out)
writeLines(c("project:","  type: website","  output-dir: _site","  render:","    - week6-inference.qmd","website:","  search: false"),file.path(out,"_quarto.yml"))
learnr2::check_tutorial(out)
old <- setwd(out); on.exit(setwd(old))
status <- system2(shQuote(quarto),c("render","week6-inference.qmd"))
if (status != 0L) stop("Prototype render failed.")
cat("Rendered:",file.path(out,"_site/week6-inference.html"),"\n")
